// שקע-מגע IEC 60617 (סמל-6.16): חצי-עיגול (כיפה) הפונה אל החדר על גזע-הזנה מהקיר.
// שקע בודד = כיפה אחת; שקע רב-מקומי = n כיפות חולקות קו-קוטר וגזע (רצועת-שקעים).
// קו מודגש אחיד; הגזע נעצר בדיוק בקו-הקוטר (אינו חוצה את הכיפה או את התווית).
function socketGang(n, opt) {
  opt = opt || {};
  const hasL = !!opt.label;
  const wt = 1.3;
  const y = hasL ? 0.62 : 0.54;                       // קו-הקוטר (בסיס-הכיפות)
  const r = Math.min(hasL ? 0.21 : 0.32, 0.48 / n);   // רדיוס-כיפה (מתכווץ לפי מס׳-המקומות)
  const out = [stem(y)];                              // גזע-הזנה יחיד מהקיר עד קו-הקוטר
  for (let i = 0; i < n; i++) {
    const cx = n === 1 ? 0.5 : 0.5 + (i - (n - 1) / 2) * (2 * r * 1.06);
    out.push(...dome(cx, y, r, { wt }));
  }
  if (hasL) out.push(label(0.5, 0.19, opt.label, labelHf(opt.label)));
  return out;
}
// מפסק-תאורה IEC 60617 (סמל-7.1): נקודת-ציר מלאה על הקיר + n מוטות-מנוף נטויים אל החדר,
// מניפה מקדקוד-משותף. n מוטות = n מעגלים (חד/דו/תלת-קוטבי). קו-מנוף מודגש אחיד.
function switchGang(n, opt) {
  opt = opt || {};
  const px = 0.5, py = 0.70, len = 0.46;              // ציר-המתג (קרוב לקיר) + אורך-מנוף
  const out = [stem(py), circle(px, py, 0.05, { fill: true })];
  const a0 = -55 * Math.PI / 180, spread = 22 * Math.PI / 180; // בסיס ~55° מעל האופק, ימינה-מעלה
  for (let i = 0; i < n; i++) {
    const a = a0 + (i - (n - 1) / 2) * spread;
    out.push(line(px, py, px + len * Math.cos(a), py + len * Math.sin(a), { wt: 1.3 }));
  }
  if (opt.label) out.push(label(0.5, 0.93, opt.label, 0.2));
  return out;
}
// סמן-מסומן: צורת-בסיס (עיגול/מלבן) + תווית קצרה. הבסיס ה"נקי" שמחליף את התיבה-הגסה.
function marker(text, shape, opt) {
  opt = opt || {};
  const out = [];
  let cy = 0.54, stemTo = 0.82;
  // הגזע נעצר בשפת-התיבה הפונה-לקיר (אינו חוצה את הצורה/הטקסט)
  if (shape === 'rect') { out.push(rect(0.17, 0.26, 0.83, 0.82, { rad: 0.06 })); cy = 0.54; stemTo = 0.82; }
  else if (shape === 'circle') { out.push(circle(0.5, 0.5, 0.32)); cy = 0.5; stemTo = 0.82; }
  else if (shape === 'square') { out.push(rect(0.2, 0.22, 0.8, 0.82)); cy = 0.52; stemTo = 0.82; }
  if (opt.stem !== false) out.unshift(stem(stemTo));
  out.push(label(0.5, cy, text, opt.hf || labelHf(text), opt.bold ? { bold: true } : null));
  return out;
}

