// ---------------------------------------------------------------------------
// resolve: מקבל key / שם / item{en,he,name,type,category,description} → הגדרת-סמל
// ---------------------------------------------------------------------------
function resolveKey(typeOrItem) {
  if (typeOrItem == null) return null;
  if (typeof typeOrItem === 'string') {
    if (SYMBOLS[typeOrItem]) return typeOrItem;                 // מפתח ישיר
    return resolveKey({ name: typeOrItem });
  }
  const it = typeOrItem;
  // key מפורש מנצח
  if (it.key && SYMBOLS[it.key]) return it.key;
  const s = [it.en, it.he, it.name, it.heName, it.description, it.type, it.class]
    .filter(Boolean).join(' | ');
  for (const [re, key] of NAME_MAP) if (re.test(s)) return key;
  if (it.category && CATEGORY_DEFAULT[it.category]) return CATEGORY_DEFAULT[it.category];
  for (const [re, key] of DISC_FALLBACK) if (re.test(s)) return key;
  return null;
}

function symbolFor(typeOrItem) {
  const key = resolveKey(typeOrItem);
  if (!key) return null;
  const sym = SYMBOLS[key];
  // אם נמסר item עם מידות אמיתיות — נצרף אותן על-פני ברירת-המחדל (ללא שינוי הרישום)
  if (typeOrItem && typeof typeOrItem === 'object') {
    const w = num(typeOrItem.width_mm ?? typeOrItem.w ?? typeOrItem.width);
    const h = num(typeOrItem.height_mm ?? typeOrItem.h ?? typeOrItem.height);
    const d = num(typeOrItem.depth_mm ?? typeOrItem.d ?? typeOrItem.depth);
    if (w != null || h != null || d != null) {
      return Object.assign({}, sym, { dims: { w: w ?? sym.dims.w, h: h ?? sym.dims.h, d: d ?? sym.dims.d } });
    }
  }
  return sym;
}
function num(v) { const n = Number(v); return Number.isFinite(n) ? n : null; }
const resolve = symbolFor;
function listSymbols() { return Object.keys(SYMBOLS); }

