// ---------------------------------------------------------------------------
// עוזרי-פרימיטיב (תיבת-יחידה מנורמלת, y כלפי-מטה)
// ---------------------------------------------------------------------------
const line = (x1, y1, x2, y2, o) => Object.assign({ t: 'line', x1, y1, x2, y2 }, o);
const rect = (x0, y0, x1, y1, o) => Object.assign({ t: 'rect', x0, y0, x1, y1 }, o);
const circle = (cx, cy, r, o) => Object.assign({ t: 'ellipse', cx, cy, r }, o);
const arc = (x0, y0, x1, y1, a0, sweep, o) => Object.assign({ t: 'arc', x0, y0, x1, y1, a0, sweep }, o);
const poly = (pts, o) => Object.assign({ t: 'poly', pts }, o);
const label = (cx, cy, text, hf, o) => Object.assign({ t: 'label', cx, cy, text, hf: hf == null ? 0.34 : hf }, o);

// עוזרים מורכבים ---------------------------------------------------------------
// גזע מהקיר (y=1) עד y0
const stem = (y0, cx) => line(cx == null ? 0.5 : cx, 1.0, cx == null ? 0.5 : cx, y0);
// חצי-עיגול "כיפה" הפונה אל החדר (שטוח כלפי הקיר). cx,cy=מרכז-הקוטר, r=רדיוס
function dome(cx, cy, r, o) {
  return [arc(cx - r, cy - r, cx + r, cy + r, 180, 180, o), line(cx - r, cy, cx + r, cy, o)];
}
// שסתום/ברז ISO — "פרפר" אנכי: שני משולשים נפגשים בקדקוד-מרכזי, בסיסים למעלה/למטה.
// הקונבנציה המקצועית לשסתום/ברז בתכניות מים/גז (מחליף עיגול-סתמי בסמל-שסתום אמיתי).
function bowtie(cx, cy, r, o) {
  return [
    poly([cx - r, cy - r, cx + r, cy - r, cx, cy], Object.assign({ closed: true }, o)),
    poly([cx - r, cy + r, cx + r, cy + r, cx, cy], Object.assign({ closed: true }, o)),
  ];
}
// סמל-הארקה IEC: גזע + שלושה קווים אופקיים מתקצרים
function earth(cx, cy, w) {
  return [
    line(cx, cy - w * 0.9, cx, cy),
    line(cx - w, cy, cx + w, cy),
    line(cx - w * 0.6, cy + w * 0.5, cx + w * 0.6, cy + w * 0.5),
    line(cx - w * 0.25, cy + w * 0.95, cx + w * 0.25, cy + w * 0.95),
  ];
}
// קשתות-פיזור (חיישן/קול)
function waves(cx, cy, r, n, a0, sweep) {
  const out = [];
  for (let i = 1; i <= n; i++) { const rr = r * i / n; out.push(arc(cx - rr, cy - rr, cx + rr, cy + rr, a0, sweep)); }
  return out;
}
// חץ קטן (ראש חץ) בכיוון dir ('up'|'down'|'left'|'right') סביב (x,y) בגודל s
function arrowHead(x, y, dir, s) {
  const m = { up: [[-s, s], [0, 0], [s, s]], down: [[-s, -s], [0, 0], [s, -s]], left: [[s, -s], [0, 0], [s, s]], right: [[-s, -s], [0, 0], [-s, s]] }[dir];
  return poly([x + m[0][0], y + m[0][1], x + m[1][0], y + m[1][1], x + m[2][0], y + m[2][1]]);
}
// גובה-גופן אוטומטי לפי אורך-הטקסט — שומר תוויות בתוך התיבה (מונע "תוויות ענק")
function labelHf(txt, cap) {
  const L = (txt || '').length;
  const base = L <= 2 ? 0.30 : L <= 4 ? 0.20 : L <= 6 ? 0.16 : 0.13;
  return Math.min(base, cap == null ? 0.30 : cap);
}
// גוף-תאורה לינארי (LED/פלואורסצנט): תעלה דקה מחולקת ל-n מקטעים (קונבנציה: קו-אור עם שנתות)
function linearLight(n, opt) {
  opt = opt || {};
  const y0 = opt.y0 == null ? 0.40 : opt.y0, y1 = opt.y1 == null ? 0.60 : opt.y1;
  const x0 = 0.04, x1 = 0.96, dash = opt.dash ? { dash: true } : null;
  const out = [rect(x0, y0, x1, y1, Object.assign({ rad: 0.02 }, dash))];
  for (let i = 1; i < n; i++) { const x = x0 + (x1 - x0) * i / n; out.push(line(x, y0, x, y1)); }
  if (opt.stem) out.push(stem(y1, opt.stemX));
  return out;
}

