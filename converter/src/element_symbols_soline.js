// ===== אדריכלי — דלתות (כנף + קשת-סיבוב) =====================================
// שורטט מחדש 2026-08 לפי קונבנציית-תכנית אדריכלית ישראלית (פנדור/רב-בריח/פיקוד-העורף;
// ראו research/manufacturer-blocks/SOURCES.md). גאומטריה מקורית ל-Soline.
//
// קונבנציה מקצועית לדלת-ציר בתכנית (מבט-על):
//   • הפתח = רוחב-התיבה. שתי אבני-סף (jambs) קצרות על-הקיר בשני קצוות-הפתח.
//   • הכנף מצוירת פתוחה 90° כ**מלבן-דק** (מראה עובי-כנף ~40 מ״מ) הניצב מהציר אל תוך-החדר.
//   • קשת רבע-עיגול (קלה) ממרכז=הציר, R=רוחב-הפתח, מקצה-הכנף אל המשקוף-הנגדי.
// planDoor(hinge, {thick, leafWt, dashArc, note}) — hinge 'L'|'R'.
function planDoor(hinge, opt) {
  opt = opt || {};
  const L = hinge !== 'R';
  const hx = L ? 0.05 : 0.95;             // ציר (hinge jamb)
  const ox = L ? 0.95 : 0.05;             // משקוף-נגדי (latch jamb)
  const R = Math.abs(ox - hx);            // רדיוס-סיבוב ≈ 0.90 = רוחב-הפתח
  const top = 1 - R;                       // קצה-הכנף החופשי (בתוך-החדר)
  const t = opt.thick == null ? 0.055 : opt.thick;  // עובי-כנף
  const lw = opt.leafWt || 1.3;
  const sx = L ? hx + t : hx - t;          // פאה-פנימית של הכנף
  const out = [
    // אבני-סף קצרות (frame reveal) בשני קצוות-הפתח — משקל-מסגרת מודגש (היררכיית-קו)
    line(hx, 1.0, hx, 0.88, { wt: 1.6 }), line(ox, 1.0, ox, 0.88, { wt: 1.6 }),
    // כנף פתוחה 90° כמלבן-דק (מראה עובי-כנף) — משקל-בינוני
    rect(Math.min(hx, sx), top, Math.max(hx, sx), 1.0, { wt: lw }),
    // נקודת-ציר (knuckle) בבסיס-הכנף — סימון-מקצועי לכיוון-הפתיחה
    circle(hx, 1.0, 0.02, { fill: true }),
  ];
  // קשת-סיבוב רבע-עיגול (קלה), מרכז=(hx,1), R. L: 270→360 · R: 180→270
  const ao = opt.dashArc ? { dash: true, wt: 0.7 } : { wt: 0.7 };
  out.push(arc(hx - R, 1 - R, hx + R, 1 + R, L ? 270 : 180, 90, ao));
  if (opt.note) out.push(label(L ? 0.62 : 0.38, 0.5, opt.note, labelHf(opt.note, 0.16)));
  return out;
}
