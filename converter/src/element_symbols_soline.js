// (1) פורמט דו״ח: { plan, elev }. plan/elev = מערך פרימיטיבים
//     בדיוק כפי שהם (הרנדרר יודע לצייר t=line/rect/ellipse/arc/poly/label).
function toReportDef(symOrKey) {
  const sym = typeof symOrKey === 'string' ? SYMBOLS[symOrKey] : symOrKey;
  if (!sym) return null;
  return { plan: sym.plan, elev: sym.elev || sym.plan };
}

// (2) פורמט GLYPHS/BLOCKS_2D של DXF: mm מקומי, נק׳-הכנסה (0,0) על הקיר, +Y אל החדר.
//     ממיר תיבת-יחידה (y↓, קיר ב-y=1) ל-DXF (y↑ מהקיר): Xmm=(x-0.5)*W · Ymm=(1-y)*H.
//     קשתות/אליפסות מדוגמות ל-polylines (עמיד להיפוך-y); עיגול אמיתי נשמר כ-{circle}.
function toDxf2dGlyph(symOrKey, opt) {
  opt = opt || {};
  const sym = typeof symOrKey === 'string' ? SYMBOLS[symOrKey] : symOrKey;
  if (!sym) return null;
  const W = opt.w || sym.dims.w || 100, H = opt.h || sym.dims.h || 100;
  const X = (u) => (u - 0.5) * W, Y = (v) => (1 - v) * H;
  const out = [];
  for (const p of (opt.view === 'elev' && sym.elev ? sym.elev : sym.plan)) {
    if (p.t === 'line') out.push([[X(p.x1), Y(p.y1)], [X(p.x2), Y(p.y2)]]);
    else if (p.t === 'rect') out.push([[X(p.x0), Y(p.y0)], [X(p.x1), Y(p.y0)], [X(p.x1), Y(p.y1)], [X(p.x0), Y(p.y1)], [X(p.x0), Y(p.y0)]]);
    else if (p.t === 'poly') { const pl = []; for (let i = 0; i + 1 < p.pts.length; i += 2) pl.push([X(p.pts[i]), Y(p.pts[i + 1])]); if (p.closed && pl.length) pl.push(pl[0].slice()); out.push(pl); }
    else if (p.t === 'ellipse') {
      const rx = p.r * W, ry = p.r * H;
      if (Math.abs(rx - ry) < 1e-6) out.push({ circle: [X(p.cx), Y(p.cy), rx] });
      else { const pl = []; for (let i = 0; i <= 32; i++) { const a = i / 32 * 2 * Math.PI; pl.push([X(p.cx) + rx * Math.cos(a), Y(p.cy) - ry * Math.sin(a)]); } out.push(pl); }
    } else if (p.t === 'arc') {
      const cx = (p.x0 + p.x1) / 2, cy = (p.y0 + p.y1) / 2, rx = (p.x1 - p.x0) / 2, ry = (p.y1 - p.y0) / 2;
      const pl = []; const steps = 28;
      for (let i = 0; i <= steps; i++) { const a = (p.a0 + p.sweep * i / steps) * Math.PI / 180; pl.push([X(cx + rx * Math.cos(a)), Y(cy + ry * Math.sin(a))]); }
      out.push(pl);
    } // label מושמט ב-DXF-2D (התוויות נכתבות בערוץ-הטקסט הנפרד); נחשוף אותן בנפרד:
    if (p.t === 'label') out.push({ label: [X(p.cx), Y(p.cy), p.text, (p.hf || 0.34) * H] });
  }
  return out;
}

