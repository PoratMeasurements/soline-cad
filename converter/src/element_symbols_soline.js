  opt = opt || {};
  const y0 = opt.y0 == null ? 0.36 : opt.y0, y1 = opt.y1 == null ? 0.64 : opt.y1;
  const mid = (y0 + y1) / 2, g = (y1 - y0) * 0.16, fw = opt.frameWt || 1.2;
