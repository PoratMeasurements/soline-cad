package il.co.soline.measure.geometry

import kotlin.math.abs
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.hypot
import kotlin.math.sin
import kotlin.math.sqrt

/**
 * מנוע-הטרילטרציה של Soline Measure — קביעת מרחקים/מיקומים ביחס לקו-ייחוס (Datum)
 * ופתרון-זווית משלושת-אורכי-המשולש (חוק-הקוסינוסים).
 *
 * במקום לגרור קודקודים על המסך, המודד קובע גאומטריה מדויקת ע"י **מדידות-משנה**
 * (מרחקים) מקווי-ייחוס / קווי-Datum. אובייקט Kotlin טהור — בלי Android/Compose —
 * כדי שיהיה נבדק, מהיר, וניתן-לשימוש-חוזר בכל שכבה.
 *
 * מוסכמות (זהות ל-[WallBuilder]):
 *  - מערכת-צירים 2D במ"מ; +X מזרחה, +Y "מעלה" (CCW חיובי).
 *  - "נורמל-שמאל" של קטע a→b הוא (‎-dy, dx) — צד ה-CCW של כיוון-ההליכה.
 *  - כל הזוויות המוחזרות במעלות, מנורמלות ל-(‎-180, 180].
 *
 * עמידות-קלט: פונקציית-הפרימיטיב [twoCircleIntersection] מחזירה null כאשר אין
 * חיתוך אמיתי (מעגלים רחוקים/מוכלים/קונצנטריים), אך סופגת רעש-מדידה קטן
 * (משיקות-כמעט) ע"י קיזוז-שורש שלילי-זעיר לאפס. הפונקציות שמעליה
 * ([angleByDistances]) לעולם אינן קורסות — בהיעדר-חיתוך הן מחזירות את
 * הנקודה-הקרובה-ביותר על ציר-הבסיס (fallback "nearest").
 */
object Trilateration {

    /** נקודה ב-2D במ"מ. תואמת-מבנה ל-[WallBuilder.Pt] אך עצמאית לשכבת-הגאומטריה. */
    data class Pt(val x: Double, val y: Double)

    private const val EPS = 1e-9

    // ------------------------------------------------------------------
    // פרימיטיב: חיתוך שני-מעגלים (בסיס כל טרילטרציה)
    // ------------------------------------------------------------------

    /**
     * חיתוך שני-מעגלים — **הפרימיטיב של הטרילטרציה**.
     *
     * מוצא את שתי-הנקודות שבהן נחתכים מעגל שמרכזו [c1] ורדיוסו [r1] עם מעגל
     * שמרכזו [c2] ורדיוסו [r2]. זהו הבסיס לכל "קביעת-נקודה-לפי-שני-מרחקים":
     * המודד יורה מרחק מכל אחת משתי-נקודות-ייחוס ידועות, ונקודת-היעד היא אחד
     * משני-החיתוכים.
     *
     * סדר-ההחזרה קבוע ודטרמיניסטי:
     *  - **first**  — החיתוך בצד ה-CCW (שמאל) של הווקטור [c1]→[c2].
     *  - **second** — החיתוך בצד ה-CW (ימין).
     * במקרה-משיק (חיתוך-יחיד) שתי-הנקודות זהות.
     *
     * @param c1 מרכז המעגל הראשון (נקודת-ייחוס A).
     * @param r1 רדיוס (המרחק הנמדד מ-A ליעד), במ"מ. חייב ≥ 0.
     * @param c2 מרכז המעגל השני (נקודת-ייחוס B).
     * @param r2 רדיוס (המרחק הנמדד מ-B ליעד), במ"מ. חייב ≥ 0.
     * @return זוג (שמאל, ימין) של נקודות-החיתוך, או **null** אם אין חיתוך אמיתי:
     *         מרכזים-חופפים (d≈0), מעגלים-רחוקים (d>r1+r2), או מעגל-מוכל (d<|r1-r2|),
     *         מעבר לסבולת-רעש זעירה. רדיוס שלילי מטופל כ-null.
     */
    fun twoCircleIntersection(c1: Pt, r1: Double, c2: Pt, r2: Double): Pair<Pt, Pt>? {
        if (r1 < 0.0 || r2 < 0.0) return null
        val dx = c2.x - c1.x
        val dy = c2.y - c1.y
        val d = hypot(dx, dy)
        if (d < EPS) return null // מרכזים חופפים — אינסוף-חיתוכים או אף-אחד

        // סבולת-רעש יחסית לגודל-הבעיה (מ"מ), כדי לא לפסול משיקות-כמעט מרעש-לייזר.
        val tol = 1e-6 * (abs(r1) + abs(r2) + d) + 1e-9
        if (d > r1 + r2 + tol) return null           // רחוקים מדי — אין חיתוך
        if (d < abs(r1 - r2) - tol) return null       // האחד מוכל בשני — אין חיתוך

        // a = היטל המרחק ממרכז-1 אל "קו-הרדיקל" לאורך הציר c1→c2.
        val a = (r1 * r1 - r2 * r2 + d * d) / (2.0 * d)
        val h2 = r1 * r1 - a * a
        val h = if (h2 <= 0.0) 0.0 else sqrt(h2) // קיזוז שורש-שלילי-זעיר (משיק)

        // p = הנקודה על הציר c1→c2 שממנה "מתפצל" גובה-החיתוך h.
        val ux = dx / d
        val uy = dy / d
        val px = c1.x + a * ux
        val py = c1.y + a * uy

        // הנורמל-שמאל של הכיוון c1→c2 הוא (‎-uy, ux). first = צד-שמאל (CCW).
        val ox = -uy * h
        val oy = ux * h
        val left = Pt(px + ox, py + oy)
        val right = Pt(px - ox, py - oy)
        return left to right
    }

    // ------------------------------------------------------------------
    // Angle by Distances (חוק-הקוסינוסים)
    // ------------------------------------------------------------------

    /**
     * **זווית-לפי-מרחקים** — פתרון-זווית בטרילטרציה (חוק-הקוסינוסים).
     *
     * בהינתן קו-בסיס בין שתי-נקודות-ייחוס [a] ו-[b] ואורכו-הנמדד [distAB],
     * ושני-מרחקים נמדדים אל נקודת-קצה שלישית — [tipFromA] מ-A ו-[distToTip]
     * מ-B — הפונקציה פותרת את מיקום-הקצה בטרילטרציה (חיתוך שני-מעגלים).
     * מכאן אפשר לגזור את **הזווית** של הקו A→קצה מול קו-הבסיס, בלי לגרור דבר.
     *
     * הגאומטריה **מונעת-מדידה**: משתמשים ב-[distAB] כדי למקם נקודת-בסיס
     * אפקטיבית B' במרחק [distAB] מ-A **לאורך הכיוון** [a]→[b]. כך המדידה
     * (ולא המיקום-הגרפי המקורי של [b]) היא הקובעת. אם [a] ו-[b] חופפים,
     * ברירת-המחדל היא כיוון +X.
     *
     * בחירת-הפתרון: מוחזר החיתוך בצד ה-CCW (שמאל) של קו-הבסיס — הקצה ש"מעל"
     * הבסיס, המוסכמה הטבעית לפינת-חדר הנפתחת שמאלה.
     *
     * עמידות: אם המרחקים אינם יוצרים משולש תקין (משולש-אי-שוויון מופר מרעש),
     * מוחזרת הנקודה-הקרובה-ביותר על ציר-הבסיס (fallback), ולעולם לא נזרקת שגיאה.
     *
     * @param a          נקודת-ייחוס A (קצה קו-הבסיס).
     * @param b          נקודת-ייחוס B (קובעת כיוון-בסיס בלבד; המרחק נלקח מ-[distAB]).
     * @param distAB     אורך קו-הבסיס הנמדד A→B, במ"מ.
     * @param distToTip  המרחק הנמדד מ-B אל נקודת-הקצה, במ"מ.
     * @param tipFromA   המרחק הנמדד מ-A אל נקודת-הקצה, במ"מ.
     * @return מיקום נקודת-הקצה (Pt) במערכת-הצירים של [a]/[b].
     */
    fun angleByDistances(a: Pt, b: Pt, distAB: Double, distToTip: Double, tipFromA: Double): Pt {
        // כיוון-הבסיס מ-A אל B (או +X אם חופפים).
        var ux = b.x - a.x
        var uy = b.y - a.y
        val ulen = hypot(ux, uy)
        if (ulen < EPS) { ux = 1.0; uy = 0.0 } else { ux /= ulen; uy /= ulen }

        // נקודת-בסיס אפקטיבית לפי האורך-הנמדד.
        val bEff = Pt(a.x + distAB * ux, a.y + distAB * uy)

        val hit = twoCircleIntersection(a, tipFromA, bEff, distToTip)
        if (hit != null) return hit.first // צד-שמאל (CCW) — הקצה שמעל הבסיס

        // fallback "nearest": המשולש לא נסגר — היטל-הקצה על ציר-הבסיס.
        // מחשבים את היטל-המרחק a לאורך הציר לפי אותה נוסחת קו-רדיקל, ומצמידים.
        val d = maxOf(distAB, EPS)
        val aProj = ((tipFromA * tipFromA - distToTip * distToTip + d * d) / (2.0 * d))
            .coerceIn(0.0, d)
        return Pt(a.x + aProj * ux, a.y + aProj * uy)
    }

    // ------------------------------------------------------------------
    // Corner by Distance — פינה במרחק-נמדד בלי לשנות כיוון-קו
    // ------------------------------------------------------------------

    /**
     * **פינה-לפי-מרחק** ("Corner by Distance").
     *
     * ממקמת נקודה במרחק-נמדד [distance] מפינת-ייחוס [fromCorner] **לאורך כיוון-קו
     * נתון** [alongDir], בלי לשנות את כיוון-הקו. זו הדרך המקצועית לקבוע קצה-קיר
     * מדויק: הכיוון כבר ידוע (הקו קיים), ורק המרחק נמדד בלייזר.
     *
     * [alongDir] הוא **וקטור-כיוון** (לא חייב להיות באורך-יחידה) — הוא מנורמל
     * פנימית. מרחק שלילי מזיז אחורה לאורך אותו כיוון.
     *
     * @param fromCorner פינת-הייחוס שממנה מודדים.
     * @param alongDir   וקטור-כיוון-הקו (יכול להיות הפרש שתי-נקודות על הקו).
     * @param distance   המרחק הנמדד לאורך הכיוון, במ"מ.
     * @return הנקודה החדשה; אם [alongDir] אפס (כיוון לא-מוגדר) מוחזרת [fromCorner].
     */
    fun cornerByDistance(fromCorner: Pt, alongDir: Pt, distance: Double): Pt {
        val len = hypot(alongDir.x, alongDir.y)
        if (len < EPS) return fromCorner // אין כיוון — אין לאן להזיז
        val ux = alongDir.x / len
        val uy = alongDir.y / len
        return Pt(fromCorner.x + distance * ux, fromCorner.y + distance * uy)
    }

    // ------------------------------------------------------------------
    // Line Orientation by Reference — אוריינטציה מול קו-ייחוס
    // ------------------------------------------------------------------

    /**
     * **כיוון-קו-לפי-ייחוס** ("Line Orientation by Reference").
     *
     * קובעת את **אזימוט-הקו** (bearing) שלנו ע"י מדידת שני-מרחקים-ניצבים אל קו-ייחוס
     * ידוע [refA]→[refB]: [d1] נמדד בקצה שליד [refA], ו-[d2] בקצה שליד [refB].
     * ההפרש בין ההיסטים לאורך אורך-הייחוס נותן את **הנטייה** של הקו שלנו מול
     * קו-הייחוס; מוסיפים אותה לאזימוט-הייחוס ומקבלים את האזימוט-המוחלט.
     *
     * מוסכמת-סימן: היסט חיובי הוא לצד ה-CCW (שמאל) של כיוון-הייחוס. אם [d2]>[d1]
     * הקו "מתרחק" בקצה-B ולכן נוטה CCW (זווית חיובית).
     *
     * @param refA  קצה-א' של קו-הייחוס.
     * @param refB  קצה-ב' של קו-הייחוס.
     * @param d1    ההיסט-הניצב מהקו שלנו לקו-הייחוס, בקצה שליד [refA], במ"מ.
     * @param d2    ההיסט-הניצב, בקצה שליד [refB], במ"מ.
     * @return אזימוט-הקו שלנו במעלות, מנורמל ל-(‎-180, 180]. אם קו-הייחוס
     *         מנוון (אורך≈0) מוחזר 0.0.
     */
    fun lineOrientationByReference(refA: Pt, refB: Pt, d1: Double, d2: Double): Double {
        val bx = refB.x - refA.x
        val by = refB.y - refA.y
        val refLen = hypot(bx, by)
        if (refLen < EPS) return 0.0 // קו-ייחוס מנוון — אין כיוון להסתמך עליו
        val refBearing = atan2(by, bx)
        val tilt = atan2(d2 - d1, refLen) // נטייה מהפרש-ההיסטים לאורך הייחוס
        return normalizeDeg(Math.toDegrees(refBearing + tilt))
    }

    // ------------------------------------------------------------------
    // Datum helpers — מיקום מקווי-אפס (X,Y)
    // ------------------------------------------------------------------

    /**
     * **מיקום-מ-Datum** ("Position by Datum / Set Corner from Datum").
     *
     * ממקמת נקודה יחסית לקווי-האפס (Datum) של השטח: מוסיפים היסט [dx] לקו-האפס
     * האנכי ([datumX]) והיסט [dy] לקו-האפס האופקי ([datumY]). זהו הבסיס למערכת-
     * קואורדינטות-שטח מקצועית שבה כל מידה נמדדת מאותם שני-קווים קבועים.
     *
     * @param datumX ערך-ה-X של קו-האפס (Datum האנכי), במ"מ.
     * @param datumY ערך-ה-Y של קו-האפס (Datum האופקי), במ"מ.
     * @param dx     ההיסט הנמדד לאורך X, במ"מ.
     * @param dy     ההיסט הנמדד לאורך Y, במ"מ.
     * @return הנקודה המוחלטת Pt(datumX+dx, datumY+dy).
     */
    fun positionFromDatum(datumX: Double, datumY: Double, dx: Double, dy: Double): Pt =
        Pt(datumX + dx, datumY + dy)

    // ------------------------------------------------------------------
    // עזרי-נוחות (public — שימושיים ל-UI וחישובי-זווית)
    // ------------------------------------------------------------------

    /** המרחק (מ"מ) בין שתי-נקודות. */
    fun distance(a: Pt, b: Pt): Double = hypot(a.x - b.x, a.y - b.y)

    /**
     * הזווית בקודקוד [vertex] בין הזרוע אל [p1] לזרוע אל [p2], במעלות (0..180],
     * מנורמלת ל-ערך-מוחלט. שימושי לגזירת "זווית-הפינה" אחרי [angleByDistances].
     * מחזיר 0.0 אם אחת-הזרועות מנוונת.
     */
    fun angleAtVertex(vertex: Pt, p1: Pt, p2: Pt): Double {
        val a1 = atan2(p1.y - vertex.y, p1.x - vertex.x)
        val a2 = atan2(p2.y - vertex.y, p2.x - vertex.x)
        if (!a1.isFinite() || !a2.isFinite()) return 0.0
        return abs(normalizeDeg(Math.toDegrees(a2 - a1)))
    }

    /** וקטור-כיוון-יחידה מזווית במעלות (0°=+X, CCW חיובי). */
    fun unitFromDeg(deg: Double): Pt {
        val r = Math.toRadians(deg)
        return Pt(cos(r), sin(r))
    }

    /** מנרמל זווית (מעלות) לתחום (‎-180, 180]. */
    fun normalizeDeg(deg: Double): Double {
        var d = deg % 360.0
        if (d <= -180.0) d += 360.0
        if (d > 180.0) d -= 360.0
        return d
    }
}
