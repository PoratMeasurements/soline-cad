package il.co.soline.measure.geometry

import kotlin.math.abs
import kotlin.math.cos
import kotlin.math.sin

/**
 * FloorLevelSolver — המתמטיקה של סקר-מישוריות (רצפה/תקרה) מנתוני ה-Leica X6.
 *
 * ── מה המכשיר שולח (ראה device/LaserBle.kt · LEICA_MEAS) ──────────────────────
 * ה-X6 מעביר בבלוטות' Reading(distanceMm, vAngleDeg, ts): **מרחק-אלכסוני** (slant)
 * ו**זווית-נטייה אנכית** (inclination). הוא **אינו** מעביר זווית-אופקית ב-BLE, לכן
 * כל החישוב כאן מבוסס על מדידה מ**תחנה קבועה** (חצובה) — מרחק + זווית-אנכית בלבד,
 * וזה מספיק כדי לחלץ את ה**גובה (Z)** של כל נקודה.
 *
 * ── הגאומטריה ─────────────────────────────────────────────────────────────────
 * מרכז-אופטי של המכשיר קבוע בחלל (חצובה שלא זזה בין הנקודות). יורים לנקודה במרחק
 * אלכסוני d ובזווית-נטייה θ (מהמישור-האופקי). מפרקים את הקרן:
 *
 *      רכיב אנכי  (גובה)   Z  =  d · sin(θ)      ← ההפרש-האנכי מ­מרכז-המכשיר
 *      רכיב אופקי (מרחק)   H  =  d · cos(θ)      ← המרחק-האופקי בתוכנית
 *
 * ── מוסכמת-הסימן (θ ו-Z) ─────────────────────────────────────────────────────
 * θ נמדד מהמישור-האופקי, **חיובי כלפי מעלה** (לכיוון התקרה), שלילי כלפי מטה (לרצפה)
 * — המוסכמה הרגילה של חיישן-הנטייה ב-DISTO (אופקי = 0°). מכאן, ישירות מהנוסחה:
 *   · נקודת-**רצפה** (יורים למטה, θ<0)  →  Z = d·sin(θ) < 0   (מתחת למכשיר)
 *   · נקודת-**תקרה** (יורים למעלה, θ>0) →  Z = d·sin(θ) > 0   (מעל המכשיר)
 * Z הוא הגובה-המסומן של הנקודה ביחס למכשיר; הסימן שלו הוא סימן θ.
 *
 * ── סטייה (ההפרש שמיכאל רוצה) ────────────────────────────────────────────────
 * מודדים תחילה נקודת-ייחוס "0" ושומרים את ה-Z שלה (zeroZ). לכל נקודה אחרת:
 *
 *      deviation = pointZ − zeroZ           (מ"מ, מסומן ±)
 *
 * זהו ההפרש-האמיתי בגובה מול ה-0 — סטיית-המישוריות. מכיוון ש-0 והנקודה נמדדים
 * מאותה תחנה קבועה, ההיסט-הקבוע של גובה-המכשיר מתבטל וההפרש נקי מהנחות-גובה.
 *
 * **פירוש הסימן (עקבי לרצפה ולתקרה):**
 *   · deviation > 0  →  הנקודה **גבוהה** מ-0  (ברצפה: בליטה/גבשושית; בתקרה: גבוה יותר)
 *   · deviation < 0  →  הנקודה **נמוכה** מ-0  (ברצפה: שקע; בתקרה: צניחה/שקיעה כלפי מטה)
 * גבשושית-רצפה מקבלת תמיד סימן +, שקע תמיד −, ללא תלות בגובה-המכשיר.
 *
 * ── הנחות ומגבלות ─────────────────────────────────────────────────────────────
 *   · **תחנה קבועה**: המכשיר לא זז (בגובה או במיקום) בין נקודה לנקודה. הזזת החצובה
 *     בין מדידות פוסלת את ההשוואה מול ה-0.
 *   · אין צורך לדעת את גובה-המכשיר בפועל — הוא מתבטל בהפרש (עובדים ב-Z יחסי).
 *   · אם זווית חסרה (vAngleDeg == null, למשל DISTO D2 דו-ממדי) — נופלים חזרה
 *     לשימוש ב-**מרחק כפי-שהוא** כ-Z, וזה מסומן למשתמש כשורה "ללא זווית".
 *
 * pure-Kotlin, ללא Compose. יחידות: מ"מ ומעלות (זהה ל-Reading של LaserBle).
 */
object FloorLevelSolver {

    /**
     * הגובה-המסומן Z (מ"מ) של נקודה ביחס למרכז-המכשיר: `d · sin(θ)`.
     * שלילי לרצפה (מתחת למכשיר), חיובי לתקרה (מעל המכשיר).
     * @param vAngleDeg זווית-נטייה אנכית (מעלות, חיובי=מעלה). אם null — מחזיר את
     *                  המרחק כפי-שהוא (fallback דו-ממדי; ראה כותרת).
     */
    fun heightZ(distanceMm: Double, vAngleDeg: Double?): Double {
        if (vAngleDeg == null) return distanceMm            // fallback: אין זווית → מרחק כ-Z
        return distanceMm * sin(Math.toRadians(vAngleDeg))
    }

    /**
     * המרחק-האופקי H (מ"מ) בתוכנית: `|d · cos(θ)|`.
     * ערך-מוחלט — cos זוגי, כך שסימן-הזווית אינו משנה; המרחק-האופקי תמיד ≥ 0.
     * שימושי לפרישת-הנקודות לאורך התוכנית. אם null — מחזיר את המרחק כפי-שהוא.
     */
    fun horizontalDist(distanceMm: Double, vAngleDeg: Double?): Double {
        if (vAngleDeg == null) return distanceMm
        return abs(distanceMm * cos(Math.toRadians(vAngleDeg)))
    }

    /**
     * הסטייה-המסומנת (מ"מ) של נקודה מול ה-0: `pointZ − zeroZ`.
     * חיובי = הנקודה גבוהה מ-0; שלילי = נמוכה מ-0 (עקבי לרצפה ולתקרה).
     */
    fun deviation(pointZ: Double, zeroZ: Double): Double = pointZ - zeroZ
}
